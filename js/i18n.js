  function tr(s, depth) {
    depth = depth || 0;
    var t = s.trim(); if (!t) return s;
    var a = s.match(/^\s*/)[0], b = s.match(/\s*$/)[0];
    var key = t.replace(/\s+/g, ' ');
    var r = MAP[key];
    if (r !== undefined) return a + r + b;
    /* nama hari/bulan di dalam tanggal */
    if (KAL_RE.test(key)) {
      KAL_RE.lastIndex = 0;
      var k2 = key.replace(KAL_RE, function (w) { return KAL[w] || w; });
      if (k2 !== key) return a + (MAP[k2] !== undefined ? MAP[k2] : k2) + b;
    }
    KAL_RE.lastIndex = 0;
    for (var i = 0; i < POLA.length; i++) {
      var m = POLA[i][0].exec(key);
      if (!m) continue;
      /* bagian yang tertangkap pola ikut diterjemahkan juga (mis. "Sisa 4 hari" -> "Remaining 4 days") */
      var out = POLA[i][1].replace(/\$(\d)/g, function (_, d) {
        var g = m[+d] || '';
        return (depth < 2 && /[a-z]{2}/i.test(g)) ? tr(g, depth + 1) : g;
      });
      if (out !== key) return a + out + b;
    }
    return s;
  }
